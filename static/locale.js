function translate(value) {
    return UI_LANGUAGE === "en" && Object.hasOwn(UI_MESSAGES, value) ? UI_MESSAGES[value] : value;
}
function translateStaticUI() {
    document.documentElement.lang = UI_LANGUAGE;
    if (UI_LANGUAGE === "en") {
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        while (walker.nextNode()) {
            const node = walker.currentNode;
            if (node.parentElement?.closest("script,style")) continue;
            const original = node.nodeValue ?? "";
            const text = original.trim();
            if (Object.hasOwn(UI_MESSAGES, text)) node.nodeValue = original.replace(text, translate(text));
        }
        for (const element of document.querySelectorAll("[placeholder],[title],[aria-label]")) {
            for (const attr of ["placeholder","title","aria-label"]) {
                const value = element.getAttribute(attr);
                if (value !== null) element.setAttribute(attr, translate(value));
            }
        }
    }
    const toggle = document.querySelector("#language");
    if (!toggle) return;
    const label = document.querySelector("#language-label");
    if (label) label.textContent = UI_LANGUAGE === "en" ? "Language: English" : "Jezik: Hrvatski";
    toggle.setAttribute("aria-label", UI_LANGUAGE === "en" ? "Switch to Croatian" : "Switch to English");
    toggle.addEventListener("click", async () => {
        toggle.disabled = true;
        try {
            const meta = document.querySelector('meta[name="local-token"]');
            const response = await fetch("/api/preferences/language", {
                method: "POST",
                headers: { "Content-Type": "application/json", "X-Local-Token": meta?.content ?? "" },
                body: JSON.stringify({ language: UI_LANGUAGE === "en" ? "hr" : "en" })
            });
            if (!response.ok) throw new Error("Language preference could not be saved.");
            window.location.reload();
        } catch {
            const notification = document.querySelector("#toast");
            if (notification) {
                notification.textContent = UI_LANGUAGE === "en" ? "Language preference could not be saved." : "Postavka jezika nije spremljena.";
                notification.hidden = false;
            }
            toggle.disabled = false;
        }
    });
}
